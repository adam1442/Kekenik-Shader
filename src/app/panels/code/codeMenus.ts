import { Copy, Crosshair, Download } from "lucide-react";
import { EditorView } from "@codemirror/view";
import { copyToClipboard, toast, type MenuItem } from "@/ui";
import { getGraph, setSelection } from "@/ui/graph/graphStore";
import { registerContextMenu } from "../../contextmenu/registry";
import { downloadText } from "../../lib/download";
import { livePanes, useCode } from "./codeStore";
import { nodeAtLine } from "./sourceMap";

/** 1-based document line under `target` inside a CodeMirror view, or undefined. */
function lineUnder(target: Element): number | undefined {
  const dom = target.closest<HTMLElement>(".cm-editor");
  const view = dom ? EditorView.findFromDOM(dom) : null;
  const line = target.closest(".cm-line");
  if (!view || !line) return undefined;
  try {
    return view.state.doc.lineAt(view.posAtDOM(line)).number;
  } catch {
    return undefined;
  }
}

/** Context menus of the Code panel: `code.line` (a generated line) and `code.tab` (a file tab / pane bar). */
export function registerCodeContextMenus(): void {
  registerContextMenu("code.line", (target, _e, info) => {
    const pane = livePanes[Number(info.id ?? 0)];
    const line = lineUnder(target);
    const hit = pane && line ? nodeAtLine(pane.result, pane.file, line) : undefined;
    const known = !!hit && hit.nodeId in getGraph().nodes;
    const items: MenuItem[] = [
      {
        label: "Select source node",
        icon: Crosshair,
        disabled: !known,
        ...(known
          ? {}
          : {
              disabledReason: hit
                ? "The node lives in a subgraph that is not open"
                : "This line was not generated by a node",
            }),
        run: () => hit && setSelection([hit.nodeId]),
      },
      {
        label: "Copy line",
        icon: Copy,
        disabled: !pane || !line,
        run: () => void copyToClipboard(pane!.text.split("\n")[line! - 1] ?? ""),
      },
      {
        label: "Copy file",
        icon: Copy,
        disabled: !pane?.text,
        run: () =>
          void copyToClipboard(pane!.text).then((ok) =>
            toast.show({ title: ok ? "Copied file" : "Copy failed", kind: ok ? "success" : "danger", duration: 1500 }),
          ),
      },
    ];
    return items;
  });
  registerContextMenu("code.tab", (_t, _e, info) => {
    const [i, file] = (info.id ?? "0:").split(":") as [string, string];
    const pane = livePanes[Number(i)];
    const st = useCode.getState();
    return [
      { label: "Copy file", icon: Copy, disabled: !pane?.text, run: () => void copyToClipboard(pane!.text) },
      {
        label: "Download file",
        icon: Download,
        disabled: !pane?.text,
        run: () => pane && downloadText(file || pane.file, pane.text),
      },
      { label: "Add target pane", disabled: st.panes.length >= 3, run: () => st.addPane() },
      { label: "Close pane", disabled: st.panes.length < 2, run: () => st.removePane(Number(i)) },
    ];
  });
}
