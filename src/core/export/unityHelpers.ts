import { resolveUnityOptions } from "../codegen/unity/options";
import { SPRITE_RECT_PROP } from "../codegen/unity/emit/sections";
import type { Graph } from "../graph/types";
import { targetProfiles } from "../profiles";
import type { ExportFile } from "../profiles/types";

/** Helper script exported next to a shader that reads the Sprite Rect node . Unity cannot hand the atlas rectangle to a shader by itself. [verify → manual check `sprite-rect`] */
const SPRITE_RECT_SCRIPT = `// Generated by Kekenik Shader — KekenikSpriteRect.cs
// Feeds the sprite's rectangle inside its texture / atlas (UV units: x, y, width, height) to the hidden material property ${SPRITE_RECT_PROP}.
// Add this component to every SpriteRenderer that uses a Kekenik shader with a "Sprite Rect" node. Without it the shader sees the full texture (0, 0, 1, 1).
using UnityEngine;

[ExecuteAlways, DisallowMultipleComponent, RequireComponent(typeof(SpriteRenderer))]
public class KekenikSpriteRect : MonoBehaviour
{
    static readonly int RectId = Shader.PropertyToID("${SPRITE_RECT_PROP}");
    SpriteRenderer _renderer;
    MaterialPropertyBlock _block;
    Sprite _last;

    void OnEnable() { Apply(true); }
    void LateUpdate() { Apply(false); } // the sprite can change every frame (animation)

    void OnDisable()
    {
        if (_renderer != null) { _renderer.GetPropertyBlock(_block); _block.SetVector(RectId, new Vector4(0f, 0f, 1f, 1f)); _renderer.SetPropertyBlock(_block); }
        _last = null;
    }

    void Apply(bool force)
    {
        if (_renderer == null) _renderer = GetComponent<SpriteRenderer>();
        Sprite sprite = _renderer.sprite;
        if (sprite == null || (!force && sprite == _last)) return;
        _last = sprite;
        Texture2D tex = sprite.texture;
        Rect r = sprite.textureRect;
        if (_block == null) _block = new MaterialPropertyBlock();
        _renderer.GetPropertyBlock(_block);
        _block.SetVector(RectId, new Vector4(r.x / tex.width, r.y / tex.height, r.width / tex.width, r.height / tex.height));
        _renderer.SetPropertyBlock(_block);
    }
}
`;

/** Extra files that accompany a generated Unity shader. */
export const unityHelperFiles = (shaderText: string): ExportFile[] =>
  shaderText.includes(SPRITE_RECT_PROP)
    ? [{ path: "KekenikSpriteRect.cs", content: SPRITE_RECT_SCRIPT, language: "csharp" }]
    : [];

/** README paragraphs for the options of this graph . Empty when nothing special is switched on. */
export function unityReadmeExtras(graph: Graph): string[] {
  const tp = targetProfiles.get(graph.profileId);
  if (!tp || tp.engine !== "unity-urp") return [];
  const o = resolveUnityOptions(tp, graph.settings, graph.name);
  const l: string[] = [];
  if (o.exposeSurface)
    l.push(
      "**Surface options in the material:** `_SrcBlend` / `_DstBlend` (BlendMode enums), `_ZWrite`, `_Cull`" +
        (tp.surfaceOptions.some((d) => d.id === "alphaClip")
          ? ", `_AlphaClip` (keyword `_ALPHATEST_ON`) and `_Cutoff`"
          : "") +
        ". `_Surface` / `_Blend` are informational (hidden). Switching blend at runtime = set `_SrcBlend`, `_DstBlend`, `_ZWrite` from a script (and the render queue); colour maths such as premultiply stays as exported.",
    );
  if (o.bakedGI)
    l.push(
      "**Baked GI:** mark the renderer *Contribute GI* + *Receive GI: Lightmaps*, give the mesh lightmap UVs (UV2) and bake. Shadow-mask / mixed lighting use the URP keywords `SHADOWS_SHADOWMASK` / `LIGHTMAP_SHADOW_MIXING`.",
    );
  if (o.metaPass)
    l.push(
      "**Meta pass:** needed so Unity can bake this shader into lightmaps / probes. Scene-view *Albedo / Emissive* debug modes are not supported by the generated Meta pass.",
    );
  if (o.motionVectors)
    l.push(
      "**Motion Vectors pass:** Unity 6 (URP 17) — used by TAA, motion blur and upscalers. Skinned meshes need their previous-frame position in TEXCOORD4 (URP provides it).",
    );
  if (o.decals) l.push("**Decals:** enable *DBuffer* on the URP Decal Renderer Feature.");
  if (o.lodCrossFade) l.push("**LOD cross-fade:** enable *LOD Cross Fade* in the URP asset and on the LOD Group.");
  if (tp.family === "vfx" && (o.flipbook || o.cameraFade || o.distortion)) {
    l.push(
      "**Particle System setup (Renderer module → Custom Vertex Streams):** add exactly the streams listed in the header of the `.shader` file, in that order." +
        (o.flipbook
          ? " Flipbook blending: enable *Texture Sheet Animation*; the UV stream is the current frame, `UV2` the next frame and `AnimBlend` the blend factor."
          : "") +
        (o.cameraFade
          ? " Camera fade: tune `_CameraNearFadeDistance` / `_CameraFarFadeDistance` on the material."
          : "") +
        (o.distortion
          ? " Distortion: enable *Opaque Texture* in the URP asset; Base Color R,G = distortion vector, Alpha = strength; use Alpha blend."
          : ""),
    );
  }
  return l;
}
