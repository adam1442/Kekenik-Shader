import { CodeWriter } from "../base/writer";
import {
  ATTRIBUTES,
  ATTRIBUTE_ORDER,
  BUILTIN_UNIFORMS,
  BUILTIN_UNIFORM_ORDER,
  type BuiltinUniformName,
} from "../glsl/builtins";
import type { ExplicitUniform, Generated } from "../dialect/generate";
import { type AssembledText, defaultComment, writeHelpersAndFunctions } from "../dialect/textParts";
import { layoutWgsl } from "../dialect/layout";
import { wgslType } from "./dialect";

/** Member name of every host built-in inside the `KsFrame` block (`ks.model`, …). */
export const WGSL_FRAME_MEMBER: Record<BuiltinUniformName, string> = {
  ks_Model: "model",
  ks_View: "view",
  ks_Projection: "projection",
  ks_WorldToObject: "world_to_object",
  ks_ViewInverse: "view_inverse",
  ks_NormalMatrix: "normal_matrix",
  ks_CameraPos: "camera_pos",
  ks_ProjectionInverse: "projection_inverse",
  ks_CameraParams: "camera_params",
  ks_ScreenParams: "screen_params",
  ks_FogColor: "fog_color",
  ks_FogParams: "fog_params",
  ks_MainLightDir: "main_light_dir",
  ks_MainLightColor: "main_light_color",
  ks_AmbientColor: "ambient_color",
  ks_SpriteRect: "sprite_rect",
  ks_SpriteInfo: "sprite_info",
  ks_Time: "time",
  ks_DeltaTime: "delta_time",
  ks_SmoothDeltaTime: "smooth_delta_time",
};

export const WGSL_NAMES = { vsMain: "vs_main", fsMain: "fs_main", frame: "ks", material: "material" } as const;

/** Bind-group layout of the generated module (documented in the header, verified by the tests). */
const WGSL_GROUPS = { frame: 0, material: 1, staticSamplers: 2 } as const;

/** Spelling of a property inside the uniform block: bool is stored as u32 (bool is not host-shareable). */
const wgslBlockType = (u: ExplicitUniform): string => (u.ty === "bool" ? "u32" : wgslType(u.ty));

export type WgslText = AssembledText;

/** Assemble the single WGSL module (vertex + fragment entry points). */
export function assembleWgsl(g: Generated, profileName: string): WgslText {
  const w = new CodeWriter();
  const v = g.vertex;
  const f = g.fragment;
  w.line("// Generated by Kekenik Shader — WGSL (WebGPU) — vertex + fragment stage");
  w.line(`// Profile: ${profileName}`);
  w.line("// Do not edit: regenerate from the graph.");
  w.line(
    `// Host contract: @group(${WGSL_GROUPS.frame}) @binding(0) = KsFrame (set once per draw); @group(${WGSL_GROUPS.material}) = exposed parameters (binding 0 = KsMaterial,`,
  );
  w.line(
    `// then texture / sampler pairs); @group(${WGSL_GROUPS.staticSamplers}) = static samplers. Matrices are column-major; projection maps clip-space Z to [0, 1].`,
  );

  w.blank().line("// ── Host frame constants (fixed layout, always declared) ──");
  const frame = layoutWgsl(BUILTIN_UNIFORM_ORDER.map((n) => ({ name: n, ty: BUILTIN_UNIFORMS[n].ty })));
  w.line("struct KsFrame {");
  w.indent();
  for (const m of frame.members) {
    const n = m.name as BuiltinUniformName;
    w.line(`${WGSL_FRAME_MEMBER[n]}: ${wgslType(m.ty)}, // offset ${m.offset} — ${BUILTIN_UNIFORMS[n].doc}`);
  }
  w.dedent().line("}");
  w.line(`@group(${WGSL_GROUPS.frame}) @binding(0) var<uniform> ${WGSL_NAMES.frame}: KsFrame; // ${frame.size} bytes`);

  const values = g.uniforms.filter((u) => u.kind === "value");
  const textures = g.uniforms.filter((u) => u.kind === "texture");
  const samplerProps = g.uniforms.filter((u) => u.kind === "sampler");
  if (values.length > 0) {
    w.blank().line("// ── Exposed parameters ──");
    const lay = layoutWgsl(values.map((u) => ({ name: u.name, ty: u.ty })));
    w.line("struct KsMaterial {");
    w.indent();
    lay.members.forEach((m, i) => {
      const u = values[i]!;
      const d = defaultComment(u);
      w.line(
        `${m.name}: ${wgslBlockType(u)}, // offset ${m.offset} — ${u.property.displayName}${u.property.exposed ? "" : " (hidden)"}${d ? ` — ${d}` : ""}`,
      );
    });
    w.dedent().line("}");
    w.line(
      `@group(${WGSL_GROUPS.material}) @binding(0) var<uniform> ${WGSL_NAMES.material}: KsMaterial; // ${lay.size} bytes`,
    );
  }
  if (textures.length + samplerProps.length > 0) {
    w.blank().line("// ── Textures and samplers ──");
    let b = 1;
    for (const u of textures) {
      w.line(
        `@group(${WGSL_GROUPS.material}) @binding(${b++}) var ${u.name}: ${wgslType(u.ty)}; // ${u.property.displayName}${defaultComment(u) ? ` — ${defaultComment(u)}` : ""}`,
      );
      w.line(`@group(${WGSL_GROUPS.material}) @binding(${b++}) var ${u.name}_sampler: sampler;`);
    }
    for (const u of samplerProps)
      w.line(`@group(${WGSL_GROUPS.material}) @binding(${b++}) var ${u.name}: sampler; // ${u.property.displayName}`);
  }
  if (g.samplers.length > 0) {
    w.blank().line("// ── Static samplers (inline sampler-state nodes) ──");
    g.samplers.forEach((s, i) =>
      w.line(
        `@group(${WGSL_GROUPS.staticSamplers}) @binding(${i}) var ${s.name}: sampler; // ${s.filter} filter, ${s.wrap} wrap`,
      ),
    );
  }

  const attrs = ATTRIBUTE_ORDER.filter((a) => v.st.use.attrs.has(a));
  w.blank().line("// ── Stage inputs / outputs ──");
  w.line("struct VertexInput {");
  w.indent();
  for (const a of attrs)
    w.line(`@location(${ATTRIBUTES[a].location}) ${a}: ${wgslType(ATTRIBUTES[a].ty)}, // ${ATTRIBUTES[a].doc}`);
  w.line("@builtin(vertex_index) sv_vertex_index: u32,");
  w.line("@builtin(instance_index) sv_instance_index: u32,");
  w.dedent().line("}");
  w.blank().line("struct VertexOutput {");
  w.indent().line("@builtin(position) sv_position: vec4<f32>,");
  v.varyings.forEach((x, i) => w.line(`@location(${i}) ${x.name}: ${wgslType(x.ty)},`));
  w.dedent().line("}");
  w.blank().line("struct FragmentInput {");
  w.indent();
  f.varyings.forEach((x, i) => w.line(`@location(${i}) ${x.name}: ${wgslType(x.ty)},`));
  w.line("@builtin(front_facing) sv_front_facing: bool,");
  w.dedent().line("}");

  w.blank().line(
    "// ── Stage globals (assigned at the start of each entry point so helper functions can read them) ──",
  );
  for (const a of attrs) w.line(`var<private> ${a}: ${wgslType(ATTRIBUTES[a].ty)};`);
  w.line("var<private> ks_vertex_index: i32;");
  w.line("var<private> ks_instance_index: i32;");
  w.line("var<private> ks_front_facing: bool;");
  for (const x of f.varyings) w.line(`var<private> ${x.name}: ${wgslType(x.ty)};`);
  for (const gl of v.st.globals.values()) w.line(`var<private> ${gl.name}: ${wgslType(gl.ty)};`);

  writeHelpersAndFunctions(w, g.helpers, g.functions);

  const sections: WgslText["sections"] = [];
  w.blank();
  sections.push({ label: "Vertex", line: w.lineCount + 1 });
  w.line("@vertex");
  w.line(`fn ${WGSL_NAMES.vsMain}(vs_in: VertexInput) -> VertexOutput {`);
  w.indent();
  for (const a of attrs) w.line(`${a} = vs_in.${a};`);
  w.line("ks_vertex_index = i32(vs_in.sv_vertex_index);");
  w.line("ks_instance_index = i32(vs_in.sv_instance_index);");
  w.append(v.body);
  w.line("var vs_out: VertexOutput;");
  w.line(`vs_out.sv_position = ${v.clipFinal};`);
  for (const x of v.varyings) w.line(`vs_out.${x.name} = ${x.expr};`, x.ref);
  w.line("return vs_out;");
  w.dedent().line("}");

  w.blank();
  sections.push({ label: "Fragment", line: w.lineCount + 1 });
  w.line("@fragment");
  w.line(`fn ${WGSL_NAMES.fsMain}(fs_in: FragmentInput) -> @location(0) vec4<f32> {`);
  w.indent();
  w.line("ks_front_facing = fs_in.sv_front_facing;");
  for (const x of f.varyings) w.line(`${x.name} = fs_in.${x.name};`);
  w.append(f.body);
  w.line(`return ${f.color};`);
  w.dedent().line("}");
  return { text: w.toString(), table: w.table, sections };
}
