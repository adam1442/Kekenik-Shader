import type { UniformEntry } from "../base/layout";
import { defaultComment } from "../dialect/textParts";
import { CodeWriter } from "../base/writer";
import type { Stage } from "../../ir/types";
import { ATTRIBUTES, ATTRIBUTE_ORDER, BUILTIN_UNIFORMS, BUILTIN_UNIFORM_ORDER } from "./builtins";
import type { StageState } from "./stageGen";
import { glslType } from "./types";

export interface AssembleInput {
  stage: Stage;
  profileName: string;
  st: StageState;
  /** User uniforms (module order) — only those the stage uses are declared. */
  uniforms: readonly UniformEntry[];
  /** Varyings declared as `out` (vertex) or `in` (fragment). */
  varyings: ReadonlyArray<{ name: string; ty: Parameters<typeof glslType>[0] }>;
  /** Pre-rendered function definitions (callee-first). */
  functions: readonly CodeWriter[];
  /** Pre-rendered `void main() { … }` body (lines at depth 0, indented by the assembler). */
  main: CodeWriter;
  fragOutName?: string;
  /** Extra declaration lines emitted before the helpers (preview surface struct). */
  extra?: readonly string[];
}

/** Builds the complete shader text: version, header, precision, declarations, helpers, functions, main. */
export function assembleShader(a: AssembleInput): { text: string; table: CodeWriter["table"] } {
  const w = new CodeWriter();
  const { st } = a;
  w.line("#version 300 es");
  w.line(`// Generated by Kekenik Shader — GLSL ES 3.00 (WebGL2) — ${a.stage} stage`);
  w.line(`// Profile: ${a.profileName}`);
  w.line("// Do not edit: regenerate from the graph. Host contract (attributes, ks_* uniforms) is listed below.");
  w.line("precision highp float;").line("precision highp int;").line("precision highp sampler2D;");
  // GLSL ES 3.00 predeclares default precision for sampler2D / samplerCube only: array and 3-D samplers need an explicit statement (E9).
  const extraSamplers = new Set(a.uniforms.filter((u) => st.usedUniforms.has(u.prop)).map((u) => u.ty));
  if (extraSamplers.has("texture2DArray")) w.line("precision highp sampler2DArray;");
  if (extraSamplers.has("texture3D")) w.line("precision highp sampler3D;");
  if (extraSamplers.has("textureCube")) w.line("precision highp samplerCube;");

  if (a.stage === "vertex" && st.use.attrs.size > 0) {
    w.blank().line("// Vertex attributes (explicit locations)");
    for (const n of ATTRIBUTE_ORDER)
      if (st.use.attrs.has(n))
        w.line(`layout(location = ${ATTRIBUTES[n].location}) in ${ATTRIBUTES[n].ty} ${n}; // ${ATTRIBUTES[n].doc}`);
  }
  if (st.use.uniforms.size > 0) {
    w.blank().line("// Built-in uniforms (set by the host)");
    for (const n of BUILTIN_UNIFORM_ORDER)
      if (st.use.uniforms.has(n)) w.line(`uniform ${BUILTIN_UNIFORMS[n].ty} ${n}; // ${BUILTIN_UNIFORMS[n].doc}`);
  }
  if (st.decls.size > 0) {
    w.blank().line("// Preview emulation of engine resources (host-supplied by the Kekenik Shader preview)");
    for (const d of st.decls) w.line(d);
  }
  const used = a.uniforms.filter((u) => st.usedUniforms.has(u.prop));
  if (used.length > 0) {
    w.blank().line("// Exposed parameters");
    for (const u of used) {
      const d = defaultComment(u);
      w.line(
        `uniform ${glslType(u.ty)} ${u.name}; // ${u.property.displayName}${u.property.exposed ? "" : " (hidden)"}${d ? ` — ${d}` : ""}`,
      );
    }
  }
  if (a.varyings.length > 0) {
    w.blank().line(a.stage === "vertex" ? "// Varyings (to fragment stage)" : "// Varyings (from vertex stage)");
    for (const v of a.varyings) w.line(`${a.stage === "vertex" ? "out" : "in"} ${glslType(v.ty)} ${v.name};`);
  }
  if (a.fragOutName) w.blank().line(`out vec4 ${a.fragOutName};`);
  if (st.globals.size > 0) {
    w.blank().line("// Derived inputs (filled at the start of main)");
    for (const g of st.globals.values()) w.line(`${glslType(g.ty)} ${g.name};`);
  }
  const helpers = st.helpers.emit();
  const afterFns = a.extra ?? [];
  if (helpers.length > 0) {
    w.blank().line("// Helpers");
    helpers.forEach((h, i) => {
      if (i > 0) w.blank();
      w.raw(h);
    });
  }
  for (const f of a.functions) {
    w.blank();
    w.append(f);
  }
  if (afterFns.length > 0) {
    w.blank();
    for (const l of afterFns) w.line(l);
  }
  w.blank().line("void main() {");
  w.indent().append(a.main);
  w.dedent().line("}");
  return { text: w.toString(), table: w.table };
}
