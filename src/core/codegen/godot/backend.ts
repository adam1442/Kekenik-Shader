export const KEKENIK_GENERATOR_VERSION = "0.1.0";

interface GodotEmitOptions {
  graphName: string;
  settings: Record<string, ParamValue>;
  properties: Property[];
  keywords?: Keyword[];
  labels?: Record<string, string>;
  /** Graph node ids evaluated per vertex and interpolated (Custom Interpolator / hint), see `planStages`. */
  interpolate?: string[];
  generatorVersion?: string;
  /** Extra property ids exported as `global uniform` (in addition to `Property.godotGlobal`; must exist in Project Settings → Shader Globals). */
  globalUniforms?: string[];
}

/** `my_graph_name` — file name of the `.gdshader` (no extension). */
export const godotFileBase = (graphName: string): string =>
  graphName
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "") || "shader";
const PROFILE_LABEL: Record<string, string> = {
  "godot.spatial": "Spatial",
  "godot.canvasitem": "CanvasItem",
  "godot.spatial.vfx": "Spatial (VFX preset)",
};
const rendererLabel = (r: string): string =>
  GODOT_RENDERERS.find((x) => x.id === r)?.label.replace(" renderers", "") ?? r;

function godotHeader(o: GodotOptions, version: string): string[] {
  return [
    `// Generated by Kekenik Shader ${version}`,
    `// Target: Godot ${o.target.version}  Profile: ${PROFILE_LABEL[o.profile.id] ?? o.profile.label}  Renderer: ${rendererLabel(o.target.renderer)}`,
    "// This file was generated by Kekenik Shader. Manual edits will be lost on re-export.",
  ];
}

const doc = (s: string): string =>
  `/** ${s
    .replace(/\*\//g, "* /")
    .replace(/[\r\n]+/g, " ")
    .trim()} */`;

/**
 * canvas_item has no 3D camera, no FRONT_FACING and no view / projection matrices: an input that needs them is a clean, readable
 * "unsupported on this profile" diagnostic instead of code Godot rejects ("Unknown identifier in expression").
 */
function assertCanvasInputs(module: IRModule): void {
  const bad = new Set<string>();
  for (const exprs of [module.main.exprs, ...module.functions.map((f) => f.body.exprs)])
    for (const e of exprs) {
      if (e.op !== "input") continue;
      if (["screenPos", "faceSign", "cameraPos", "viewDir"].includes(e.input) || e.space === "view" || e.space === "clip")
        bad.add(`${e.input}${e.space ? ` (${e.space} space)` : ""}`);
    }
  if (bad.size)
    throw new UnsupportedError(
      `canvas_item is a 2D shader type: it has no 3D camera, FRONT_FACING or view / projection matrices, so ${[...bad].join(", ")} cannot be exported — use a Spatial profile`,
    );
}

function emit(irModule: IRModule, profile: ProfileDef, options: EmitOptions): EmitResult {
  // Godot helper functions cannot read built-ins: every built-in a function reads becomes a hidden parameter (E7, core/ir/lowerInputs.ts).
  if (profile.id === "godot.canvasitem") assertCanvasInputs(irModule);
  const eo = options as unknown as GodotEmitOptions;
  const tp = targetProfiles.get(profile.id);
  if (!tp || tp.engine !== "godot") throw new Error(`No Godot target profile "${profile.id}"`);
  // Engine templates (camera params, matrices, viewport size …) read built-ins too: same rule, second pass (E7b).
  const module = lowerEngineBuiltins(lowerFunctionInputs(irModule), (n) => godotEngineDeps(n, profile.id === "godot.canvasitem"));
  const o = resolveGodotOptions(tp, eo.settings);
  const canvas = o.shaderType === "canvas_item";
  const problems: ProfileProblem[] = [...o.problems];

  const spriteProps = new Set(
    canvas
      ? eo.properties.filter((p) => p.type === "texture2D" && p.referenceName === "_MainTex").map((p) => p.id)
      : [],
  );
  const refs = godotReferenceNames(eo.properties.filter((p) => !spriteProps.has(p.id)));
  problems.push(...refs.problems);
  const st = newGodotState(canvas, refs.names, spriteProps);
  const taken = new Set<string>([
    ...refs.names.values(),
    ...eo.properties.flatMap((p) => (refs.names.has(p.id) ? derivedNames(p, refs.names.get(p.id)!) : [])),
  ]);
  for (const p of eo.properties)
    if (p.type === "texture2D" && p.tilingOffset && refs.names.has(p.id)) st.tiling.add(refs.names.get(p.id)!);
  const kwDefs = (eo.keywords ?? []).filter((k) => k.definition !== "static");
  for (const k of kwDefs) {
    let name = keywordTargetName(k.referenceName, "godot");
    for (let i = 2; taken.has(name); i++) name = `${keywordTargetName(k.referenceName, "godot")}_${i}`;
    taken.add(name);
    st.keywordNames.set(keywordUniformId(k.id), { name, kind: k.kind });
  }

  const pack = makeGodotPack(st);
  const g = generate(module, pack, {
    ...(eo.labels ? { labels: eo.labels } : {}),
    ...(eo.interpolate ? { interpolate: eo.interpolate } : {}),
    dialect: { ...DEFAULT_DIALECT_OPTIONS },
    skipAlphaClip: true,
  });

  // ── uniforms ──
  const used = new Set(g.uniforms.map((u) => u.prop));
  const globals = new Set(eo.globalUniforms ?? []);
  const items: Array<{ lines: string[]; category?: string | undefined }> = [];
  let instances = 0;
  for (const p of eo.properties) {
    if (spriteProps.has(p.id) || (!p.exposed && !used.has(p.id))) continue;
    const name = refs.names.get(p.id)!;
    const isGlobal = (globals.has(p.id) || !!p.godotGlobal) && !isTextureType(p.type);
    let out = godotUniform(p, name, { global: isGlobal, keywordNote: !!p.keyword, instanceAllowed: true });
    const need = out.lines.filter((l) => l.startsWith("instance uniform")).length;
    if (out.instance && instances + need > MAX_INSTANCE_UNIFORMS)
      out = godotUniform(p, name, { global: isGlobal, keywordNote: !!p.keyword, instanceAllowed: false });
    else instances += need;
    problems.push(...out.problems);
    items.push({ lines: out.lines, category: out.category });
  }
  for (const u of g.uniforms) {
    const kw = st.keywordNames.get(u.prop);
    const k = kw && kwDefs.find((x) => keywordUniformId(x.id) === u.prop);
    if (!kw || !k) continue;
    const hint =
      k.kind === "enum"
        ? ` : hint_enum(${(k.entries ?? []).map((e) => `"${e.replace(/["\\:]/g, "")}"`).join(", ")})`
        : "";
    items.push({
      lines: [
        doc(k.displayName),
        k.kind === "boolean"
          ? `uniform bool ${kw.name} = ${k.default ? "true" : "false"};`
          : `uniform int ${kw.name}${hint} = ${Math.round(k.default)};`,
      ],
      category: k.category,
    });
    problems.push({
      rule: "godot.keyword-runtime",
      severity: "warning",
      message: `Keyword "${k.displayName}": Godot has no per-material shader keywords — exported as a runtime uniform`,
      manual: "keyword-runtime",
    });
  }
  const extra: string[] = [];
  const soft = o.softParticles && o.vfx;
  if (soft) {
    items.push({
      lines: [
        doc("Soft particles: fade start distance"),
        "uniform float soft_near : hint_range(0.0, 100.0, 0.01) = 0.0;",
        doc("Soft particles: fade end distance"),
        "uniform float soft_far : hint_range(0.0, 100.0, 0.01) = 1.0;",
      ],
    });
    st.screenTextures.add("depth");
    if (!o.transparent)
      problems.push({
        rule: "profile.option-unsupported",
        severity: "warning",
        message:
          "Soft Particles reads the depth texture and needs a transparent blend mode (the material renders in the transparent pass)",
      });
  }
  const TEX: Record<string, string> = {
    screen: "kek_screen_texture : hint_screen_texture, repeat_disable, filter_nearest",
    depth: "kek_depth_texture : hint_depth_texture, repeat_disable, filter_nearest",
    normal_roughness: "kek_normal_roughness_texture : hint_normal_roughness_texture, repeat_disable, filter_nearest",
  };
  for (const k of ["screen", "depth", "normal_roughness"] as const)
    if (st.screenTextures.has(k)) extra.push(`uniform sampler2D ${TEX[k]};`);
  if (st.screenTextures.has("normal_roughness") && o.target.renderer !== "forward_plus")
    problems.push({
      rule: "godot.renderer-unsupported",
      severity: "warning",
      message: "hint_normal_roughness_texture works only in the Forward+ renderer",
    });
  if (soft && o.target.renderer === "mobile")
    problems.push({
      rule: "godot.renderer-unsupported",
      severity: "info",
      message: "Soft particles read the depth texture; confirm it on the Mobile renderer (manual check soft-particles)",
      manual: "soft-particles",
    });

  // ── text ──
  const L: string[] = [...godotHeader(o, eo.generatorVersion ?? KEKENIK_GENERATOR_VERSION)];
  if (st.missing.size)
    L.push(`// Warning: no Godot equivalent for ${[...st.missing].sort().join(", ")} — replaced by zero.`);
  L.push(`shader_type ${o.shaderType};`);
  if (o.modes.length) L.push(`render_mode ${o.modes.join(", ")};`);
  if (o.stencil) L.push(`stencil_mode ${o.stencil};`);
  L.push("");
  const u = [...assembleUniformSections(items), ...extra];
  if (u.length) L.push(...u, "");
  const varyings = [
    ...g.vertex.varyings.map((v) => `varying ${v.ty} ${v.name};`),
    ...(canvas && o.applyModulate ? ["varying vec4 kek_modulate;"] : []),
  ];
  if (varyings.length) L.push(...varyings, "");
  const helpers = [...g.helpers, ...st.engineHelpers];
  if (helpers.length) L.push(...helpers.join("\n\n").split("\n"), "");
  for (const f of g.functions) L.push(...f.toString().replace(/\s+$/, "").split("\n"), "");
  L.push(...vertexFunction(g, o, st));
  const frag = fragmentFunction(g, o);
  if (frag.length) L.push("", ...frag);
  else L.push("", "void fragment() {", "}");
  const light = lightFunction(g, o);
  if (light.length) L.push("", ...light);
  if (light.length && (o.modes.includes("unshaded") || o.modes.includes("vertex_lighting")))
    problems.push({
      rule: "godot.light-ignored",
      severity: "warning",
      message:
        "light() is not called with render_mode unshaded / vertex_lighting — the Custom light() blocks have no effect",
      manual: "light-stage",
    });
  if (light.length)
    problems.push({
      rule: "godot.unverified-api",
      severity: "info",
      message:
        "light() stage built-ins (LIGHT, LIGHT_COLOR, ATTENUATION, DIFFUSE_LIGHT, SPECULAR_LIGHT …) are unverified-by-doc — see the manual checklist",
      manual: "light-stage",
    });
  while (L[L.length - 1] === "") L.pop();
  const text = L.join("\n") + "\n";

  for (const m of st.missing)
    problems.push({
      rule: "profile.node-unsupported",
      severity: "warning",
      message: `Built-in "${m}" has no Godot equivalent; replaced by zero`,
    });
  for (const a of st.missingAttrs)
    problems.push({
      rule: "profile.node-unsupported",
      severity: "warning",
      message: `Vertex attribute "${a}" does not exist in ${o.shaderType}; replaced by zero`,
    });
  if (st.engineTemplates.size || st.engineHelpers.size)
    problems.push({
      rule: "godot.unverified-api",
      severity: "info",
      message: "Engine templates are unverified-by-doc — see the manual checklist",
      manual: "unverified-api",
    });
  const diagnostics = [...g.diagnostics];
  for (const p of problems)
    if (p.severity === "error") diagnostics.push(makeDiagnostic("E_BACKEND_FAILED", `[${p.rule}] ${p.message}`));
  return {
    files: [{ path: `${godotFileBase(eo.graphName)}.gdshader`, content: text, language: "gdshader" }],
    diagnostics,
    problems,
    uniformBindings: g.uniforms.map((x) => ({ propId: x.prop, name: x.name, ty: x.ty })),
  };
}

/** Godot 4.x backend (`.gdshader`). Reuses the shared GLSL-family generator through a Godot dialect / pack (Decision D-9b-1). */
export const godotBackend: Backend = { id: "godot", traits: BACKEND_TRAITS.godot, emit };
