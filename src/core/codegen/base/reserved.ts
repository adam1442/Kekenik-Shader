const GLSL_ALL = [...GLSL_KEYWORDS, ...GLSL_BUILTIN_FUNCTIONS];

const RESERVED_WORDS: Readonly<Record<CodegenLang, ReadonlySet<string>>> = {
  glsl: new Set(GLSL_ALL),
  hlsl: new Set([...HLSL_KEYWORDS, ...HLSL_BUILTINS]),
  wgsl: new Set([...WGSL_KEYWORDS, ...WGSL_BUILTINS]),
  godot: new Set([...GLSL_ALL, ...GODOT_EXTRA]),
  unity: new Set([...HLSL_KEYWORDS, ...HLSL_BUILTINS, ...UNITY_EXTRA]),
};

export function isReservedWord(lang: CodegenLang, word: string): boolean {
  return RESERVED_WORDS[lang].has(word);
}
