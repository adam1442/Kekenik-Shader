export const KEKENIK_GENERATOR_VERSION = "0.1.0";
const VERTEX_SLOTS = ["positionOS", "normalOS", "tangentOS"];

/** Blocks that cost code only when something is connected to them (translucency back light). */
const OPTIONAL_BLOCKS: ReadonlySet<string> = new Set(["translucency", "thickness"]);
/** An optional block is "connected" when its output is not the block's constant default (unconnected blocks are folded to it). */
function optionalConnected(module: import("../../ir/types").IRModule, b: BlockDef): boolean {
  const o = module.outputs.find((x) => x.slot === b.id);
  const e = o ? module.main.exprs[o.value] : undefined;
  if (!e) return false;
  if (e.op !== "const") return true;
  const d = b.defaultValue;
  const want = Array.isArray(d) ? d : [typeof d === "number" ? d : 0];
  return e.value.some((v, i) => v !== (want[i] ?? 0));
}

function unityHeader(ctx: EmitCtx, version: string, extra: string[] = []): string[] {
  return [
    `// Generated by Kekenik Shader ${version}`,
    `// Target: Unity ${ctx.o.target.unity} / URP ${ctx.o.target.urp}  Profile: ${ctx.tp.label}`,
    "// This file was generated by Kekenik Shader. Manual edits will be lost on re-export.",
    ...extra,
  ];
}

function emit(module: IRModule, profile: ProfileDef, options: EmitOptions): EmitResult {
  const eo = options as unknown as UnityEmitOptions;
  const tp = targetProfiles.get(profile.id);
  if (!tp) throw new Error(`No Unity target profile "${profile.id}"`);
  const o = resolveUnityOptions(tp, eo.settings, eo.graphName);
  const sprite = tp.family === "sprite";
  const reserved = [
    ...(o.exposeSurface ? SURFACE_RESERVED : []),
    ...(tp.family === "vfx"
      ? [...(o.cameraFade ? VFX_RESERVED.cameraFade! : []), ...(o.distortion ? VFX_RESERVED.distortion! : [])]
      : []),
  ];
  const refs = unityReferenceNames(eo.properties, sprite, reserved);
  const st = newPackState(refs.names);
  for (const p of eo.properties)
    if (isTextureType(p.type)) {
      st.textureProps.add(refs.names.get(p.id)!);
      if (p.type === "texture2D" && p.tilingOffset) st.stNames.add(refs.names.get(p.id)!);
    }
  const pack = makeUnityPack(st);
  const fragmentBlocks = tp.blocks.filter(
    (b) =>
      (b.context === "fragment" &&
        (OPTIONAL_BLOCKS.has(b.id) ? optionalConnected(module, b) : module.outputs.some((x) => x.slot === b.id))) ||
      (b.context === "fragment" && !b.shownWhen && !OPTIONAL_BLOCKS.has(b.id)),
  );
  const allKeywords = unityKeywords(eo.keywords ?? [], eo.properties, refs.names);
  for (const k of allKeywords) st.keywordMacros.set(k.prop, k.macro);
  const ctx: EmitCtx = {
    o,
    tp,
    def: profile,
    st,
    gens: {},
    attrs: new Set(["a_position", "a_normal"]),
    fragmentBlocks,
    usesFace: false,
    usesVertexId: false,
    usesInstanceId: false,
    keywords: [],
    keywordPragmas: [],
    problems: [...refs.problems],
    extraAttrs: [],
    cutoffProp: false,
    implied: { spriteRect: false },
  };
  // E3: runtime alpha clip reads `_Cutoff` unless the graph drives the threshold block.
  const thr = tp.blocks.find((b) => b.id === "alphaClipThreshold");
  ctx.cutoffProp =
    o.exposeSurface &&
    o.clipCode &&
    !(thr && fragmentBlocks.some((b) => b.id === thr.id) && optionalConnected(module, thr));
  const vslots = VERTEX_SLOTS.filter((s) => module.outputs.some((x) => x.slot === s));
  const gen = (id: SliceId): void => {
    const slots = sliceSlots(ctx, id);
    if (id !== "forward" && slots.length === 0) return;
    const m = id === "forward" ? module : sliceModule(module, [...vslots, ...slots]);
    ctx.gens[id] = generate(m, pack, {
      ...(eo.labels ? { labels: eo.labels } : {}),
      ...(eo.interpolate ? { interpolate: eo.interpolate } : {}),
      dialect: { ...DEFAULT_DIALECT_OPTIONS },
    });
  };
  gen("forward");
  gen("alpha");
  gen("normals");
  if (tp.family === "lit" || tp.family === "unlit") ctx.attrs.add("a_normal");
  if (tp.family === "lit") ctx.attrs.add("a_tangent");
  // E1 / E2 attribute plumbing (after the graph's own attributes are known).
  const usedUv = ["a_uv1", "a_uv2", "a_uv3"].filter((a) => ctx.attrs.has(a as AttributeName));
  for (const g of Object.values(ctx.gens))
    for (const a of g!.vertex.st.use.attrs) if (a.startsWith("a_uv")) usedUv.push(a);
  if (tp.family === "lit") {
    if (o.bakedGI || o.metaPass) ctx.attrs.add("a_uv1");
    if (o.metaPass) ctx.attrs.add("a_uv2");
    if (o.motionVectors) ctx.extraAttrs.push("float3 positionOld : TEXCOORD4;");
    if (eo.settings.motionVectors === true && !o.target.motionVectors)
      ctx.problems.push({
        rule: "profile.option-unsupported",
        severity: "warning",
        message: `Motion Vectors pass needs Unity 6 (URP 17+); not generated for Unity ${o.target.unity}`,
      });
  }
  if (tp.family === "vfx" && o.flipbook) {
    const uv = ctx.gens.forward!.vertex.varyings.find((v) => v.expr === "a_uv0");
    if (!uv)
      ctx.problems.push({
        rule: "profile.option-unsupported",
        severity: "warning",
        message: "Flipbook frame blending needs a UV-driven graph (no UV0 input found); option ignored",
      });
    else if (usedUv.includes("a_uv1"))
      ctx.problems.push({
        rule: "profile.option-unsupported",
        severity: "warning",
        message:
          "Flipbook frame blending uses UV2 (TEXCOORD1) for the next-frame UV, but the graph already reads UV2; option ignored",
      });
    else {
      const blendIndex = Math.max(2, ...usedUv.map((a) => Number(a.slice(4)) + 1));
      ctx.attrs.add("a_uv1");
      ctx.extraAttrs.push(`float ksAnimBlend : TEXCOORD${blendIndex};`);
      ctx.flipbook = { uvVarying: uv.name, blendIndex };
    }
  }
  const all = Object.values(ctx.gens);
  for (const g of all) for (const a of g!.vertex.st.use.attrs) ctx.attrs.add(a);
  const texts = all.flatMap((g) => [
    g!.fragment.body.toString(),
    ...g!.functions.map((f) => f.toString()),
    ...Object.values(g!.fragment.slotExprs),
    g!.vertex.core.toString(),
  ]);
  ctx.usesFace = texts.some((t) => t.includes("ks_front_facing")) || (tp.family === "lit" && o.doubleSided !== "none");
  if (tp.family === "lit" && o.doubleSided !== "none" && o.cull !== "off")
    ctx.problems.push({
      rule: "profile.option-unsupported",
      severity: "warning",
      message: `Double-Sided Normals (${o.doubleSided}) only has an effect with Render Face = Both (Cull Off); currently Cull ${o.cull}`,
    });
  ctx.usesVertexId = texts.some((t) => t.includes("ks_vertex_id"));
  ctx.usesInstanceId = texts.some((t) => t.includes("KS_INSTANCE_ID"));
  ctx.implied.spriteRect = st.engineTemplates.has(SPRITE_RECT_PROP);

  ctx.keywords = usedKeywords(allKeywords, new Set(module.uniforms.map((u) => u.prop)));
  ctx.keywordPragmas = keywordPragmas(ctx.keywords, all as Generated[]);
  const sec = buildPropertySections(ctx, eo, module);
  const fam = tp.family;
  const built =
    fam === "lit"
      ? litPasses(ctx)
      : fam === "sprite"
        ? spritePasses(ctx)
        : fam === "vfx"
          ? vfxPasses(ctx)
          : {
              passes: [
                unlitForwardPass(ctx),
                ...(o.castShadows ? [shadowCasterPass(ctx)] : []),
                depthOnlyPass(ctx),
                depthNormalsPass(ctx),
              ],
              extra: [],
              headerExtra: [],
            };

  const L: string[] = [...unityHeader(ctx, eo.generatorVersion ?? KEKENIK_GENERATOR_VERSION, built.headerExtra)];
  if (ctx.keywords.length)
    L.push(`// Keywords (shader_feature_local variants): ${ctx.keywords.map((k) => k.keywords.join(" ")).join(", ")}`);
  if ((eo.keywords ?? []).some((k) => k.definition === "static"))
    L.push("// Static keywords are baked at their default value.");
  if (st.missingUniforms.size)
    L.push(`// Warning: no Unity equivalent for ${[...st.missingUniforms].sort().join(", ")} — replaced by 0.0.`);
  L.push(
    `Shader "${o.shaderName}"`,
    "{",
    "    Properties",
    "    {",
    ...sec.lines.map((l) => `        ${l}`),
    "    }",
    "    SubShader",
    "    {",
  );
  const tags = [
    `"RenderPipeline"="UniversalPipeline"`,
    `"RenderType"="${fam === "sprite" ? "Transparent" : renderTypeOf(o)}"`,
    `"Queue"="${queueOf(o)}"`,
    ...(fam === "lit" ? [`"UniversalMaterialType"="Lit"`] : []),
  ];
  L.push(`        Tags { ${tags.join(" ")} }`, "        HLSLINCLUDE");
  L.push(
    includeBlock(ctx, sec, built.extra)
      .split("\n")
      .map((l) => (l ? `        ${l}` : l))
      .join("\n"),
    "        ENDHLSL",
    "",
  );
  for (const p of built.passes)
    L.push(
      p
        .split("\n")
        .map((l) => (l ? `        ${l}` : l))
        .join("\n"),
      "",
    );
  while (L[L.length - 1] === "") L.pop();
  L.push(
    "    }",
    `    Fallback "${fam === "sprite" ? "Sprites/Default" : "Hidden/Universal Render Pipeline/FallbackError"}"`,
    "}",
  );
  let text = L.join("\n") + "\n";
  // (E4: the `sampler<Texture>` pairing is emitted structurally by the dialect — see `makeUnityDialect` — no text post-process.)
  for (const g of all) for (const s of g!.samplers) text = text.split(s.name).join(unitySamplerName(s.filter, s.wrap));

  const fw = ctx.gens.forward!;
  const problems: ProfileProblem[] = [...ctx.problems];
  for (const u of st.missingUniforms)
    problems.push({
      rule: "profile.node-unsupported",
      severity: "warning",
      message: `Built-in "${u}" has no Unity URP equivalent; replaced by 0.0`,
    });
  const variants = variantReport(text);
  if (variants.overLimit)
    problems.push({
      rule: "profile.variant-count",
      severity: "warning",
      message: `${variants.total} shader variants (limit ${variants.limit}): ${variants.passes
        .filter((p) => p.variants > 1)
        .map((p) => `${p.name} ${p.variants}`)
        .join(
          ", ",
        )}. Each variant is compiled at build time — switch off Specular Highlights / Environment Reflections / Receive Shadows, or use a leaner profile.`,
    });
  void MANUAL_CHECK_IDS;
  const diagnostics = [...fw.diagnostics];
  for (const p of ctx.problems)
    if (p.severity === "error") diagnostics.push(makeDiagnostic("E_BACKEND_FAILED", p.message));
  const file = `${o.shaderName.split("/").pop() ?? "Shader"}.shader`;
  return {
    files: [{ path: file, content: text, language: "shaderlab" }],
    diagnostics,
    problems,
    uniformBindings: fw.uniforms
      .filter((u) => !isKeywordUniform(u.prop))
      .map((u) => ({ propId: u.prop, name: u.name, ty: u.ty })),
  };
}

/** Unity URP backend (ShaderLab + HLSL). Reuses the shared HLSL generator through a Unity dialect/pack (see ARCHITECTURE decision D-9a-1). */
export const unityBackend: Backend = { id: "unity", traits: BACKEND_TRAITS.unity, emit };
