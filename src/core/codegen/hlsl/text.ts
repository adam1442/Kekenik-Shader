import { CodeWriter } from "../base/writer";
import { ATTRIBUTES, ATTRIBUTE_ORDER, BUILTIN_UNIFORMS, BUILTIN_UNIFORM_ORDER } from "../glsl/builtins";
import type { Generated } from "../dialect/generate";
import { type AssembledText, defaultComment, writeHelpersAndFunctions } from "../dialect/textParts";
import { layoutHlsl } from "../dialect/layout";
import { hlslType } from "./dialect";

/** HLSL semantics of the vertex attributes (the host binds an input layout with these names). */
export const HLSL_SEMANTIC: Record<(typeof ATTRIBUTE_ORDER)[number], string> = {
  a_position: "POSITION",
  a_normal: "NORMAL",
  a_uv0: "TEXCOORD0",
  a_color: "COLOR",
  a_tangent: "TANGENT",
  a_uv1: "TEXCOORD1",
  a_uv2: "TEXCOORD2",
  a_uv3: "TEXCOORD3",
};

export const HLSL_NAMES = { vsMain: "VSMain", psMain: "PSMain", frame: "KsFrame", material: "KsMaterial" } as const;

export type HlslText = AssembledText;

/** Assemble the single HLSL translation unit (both entry points). */
export function assembleHlsl(g: Generated, profileName: string): HlslText {
  const w = new CodeWriter();
  const v = g.vertex;
  const f = g.fragment;
  w.line("// Generated by Kekenik Shader — HLSL (Direct3D, Shader Model 5.0+) — vertex + pixel stage");
  w.line(`// Profile: ${profileName}`);
  w.line("// Do not edit: regenerate from the graph.");
  w.line(
    "// Host contract: bind KsFrame at b0, KsMaterial at b1, textures/samplers as declared, matrices uploaded column-major;",
  );
  w.line("// projection maps clip-space Z to [0, 1]; input layout semantics are listed on VSInput.");
  w.line("#pragma pack_matrix(column_major)");

  w.blank().line("// ── Host frame constants (fixed layout, always declared) ──");
  const frame = layoutHlsl(BUILTIN_UNIFORM_ORDER.map((n) => ({ name: n, ty: BUILTIN_UNIFORMS[n].ty })));
  w.line(`cbuffer ${HLSL_NAMES.frame} : register(b0)`).line("{");
  w.indent();
  for (const m of frame.members)
    w.line(
      `${hlslType(m.ty)} ${m.name}; // offset ${m.offset} — ${BUILTIN_UNIFORMS[m.name as keyof typeof BUILTIN_UNIFORMS].doc}`,
    );
  w.dedent().line("}");

  const values = g.uniforms.filter((u) => u.kind === "value");
  if (values.length > 0) {
    w.blank().line("// ── Exposed parameters ──");
    const lay = layoutHlsl(values.map((u) => ({ name: u.name, ty: u.ty })));
    w.line(`cbuffer ${HLSL_NAMES.material} : register(b1)`).line("{");
    w.indent();
    lay.members.forEach((m, i) => {
      const u = values[i]!;
      const d = defaultComment(u);
      w.line(
        `${hlslType(m.ty)} ${m.name}; // offset ${m.offset} — ${u.property.displayName}${u.property.exposed ? "" : " (hidden)"}${d ? ` — ${d}` : ""}`,
      );
    });
    w.dedent().line("}");
  }
  const textures = g.uniforms.filter((u) => u.kind === "texture");
  const samplerProps = g.uniforms.filter((u) => u.kind === "sampler");
  if (textures.length + samplerProps.length + g.samplers.length > 0) {
    w.blank().line("// ── Textures and samplers ──");
    let s = 0;
    textures.forEach((u, t) => {
      w.line(
        `${hlslType(u.ty)} ${u.name} : register(t${t}); // ${u.property.displayName}${defaultComment(u) ? ` — ${defaultComment(u)}` : ""}`,
      );
      w.line(`SamplerState ${u.name}_sampler : register(s${s++});`);
    });
    for (const u of samplerProps) w.line(`SamplerState ${u.name} : register(s${s++}); // ${u.property.displayName}`);
    for (const sm of g.samplers)
      w.line(`SamplerState ${sm.name} : register(s${s++}); // static sampler: ${sm.filter} filter, ${sm.wrap} wrap`);
  }

  const attrs = ATTRIBUTE_ORDER.filter((a) => v.st.use.attrs.has(a));
  w.blank().line("// ── Stage inputs / outputs ──");
  w.line("struct VSInput").line("{");
  w.indent();
  for (const a of attrs) w.line(`${hlslType(ATTRIBUTES[a].ty)} ${a} : ${HLSL_SEMANTIC[a]}; // ${ATTRIBUTES[a].doc}`);
  w.line("uint sv_vertex_id : SV_VertexID;");
  w.line("uint sv_instance_id : SV_InstanceID;");
  w.dedent().line("};");
  w.blank().line("struct VSOutput").line("{");
  w.indent().line("float4 sv_position : SV_POSITION;");
  v.varyings.forEach((x, i) => w.line(`${hlslType(x.ty)} ${x.name} : TEXCOORD${i};`));
  w.dedent().line("};");
  w.blank().line("struct PSInput").line("{");
  w.indent().line("float4 sv_position : SV_POSITION;");
  f.varyings.forEach((x, i) => w.line(`${hlslType(x.ty)} ${x.name} : TEXCOORD${i};`));
  w.line("bool sv_front_facing : SV_IsFrontFace;");
  w.dedent().line("};");

  w.blank().line(
    "// ── Stage globals (assigned at the start of each entry point so helper functions can read them) ──",
  );
  for (const a of attrs) w.line(`static ${hlslType(ATTRIBUTES[a].ty)} ${a};`);
  w.line("static int ks_vertex_id;");
  w.line("static int ks_instance_id;");
  w.line("static bool ks_front_facing;");
  for (const x of f.varyings) w.line(`static ${hlslType(x.ty)} ${x.name};`);
  for (const gl of v.st.globals.values()) w.line(`static ${hlslType(gl.ty)} ${gl.name};`);

  writeHelpersAndFunctions(w, g.helpers, g.functions);

  const sections: HlslText["sections"] = [];
  w.blank();
  sections.push({ label: "Vertex", line: w.lineCount + 1 });
  w.line(`VSOutput ${HLSL_NAMES.vsMain}(VSInput vs_in)`).line("{");
  w.indent();
  for (const a of attrs) w.line(`${a} = vs_in.${a};`);
  w.line("ks_vertex_id = (int)vs_in.sv_vertex_id;");
  w.line("ks_instance_id = (int)vs_in.sv_instance_id;");
  w.append(v.body);
  w.line("VSOutput vs_out;");
  w.line(`vs_out.sv_position = ${v.clipFinal};`);
  for (const x of v.varyings) w.line(`vs_out.${x.name} = ${x.expr};`, x.ref);
  w.line("return vs_out;");
  w.dedent().line("}");

  w.blank();
  sections.push({ label: "Fragment", line: w.lineCount + 1 });
  w.line(`float4 ${HLSL_NAMES.psMain}(PSInput ps_in) : SV_Target`).line("{");
  w.indent();
  w.line("ks_front_facing = ps_in.sv_front_facing;");
  for (const x of f.varyings) w.line(`${x.name} = ps_in.${x.name};`);
  w.append(f.body);
  w.line(`return ${f.color};`);
  w.dedent().line("}");
  return { text: w.toString(), table: w.table, sections };
}
