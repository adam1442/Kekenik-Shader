// Generates src/app/pro/licenses.generated.ts and THIRD_PARTY_LICENSES.md from the actual production dependency tree.
// Fails loudly if any copyleft (GPL/AGPL/LGPL) dependency is found.
// Usage: node scripts/gen-licenses.mjs
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const read = (p) => JSON.parse(readFileSync(p, "utf8"));
const pkg = read(join(root, "package.json"));
const seen = new Map();

const normalizeUrl = (u) => {
  if (!u) return "";
  let s = String(u).trim().replace(/^git\+/, "").replace(/\.git$/, "");
  if (s.startsWith("git://github.com/")) s = "https://github.com/" + s.slice("git://github.com/".length);
  if (s.startsWith("github:")) s = "https://github.com/" + s.slice("github:".length);
  if (/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(s)) s = `https://github.com/${s}`;
  return s;
};

const readLicenseFile = (pkgDir) => {
  if (!existsSync(pkgDir)) return null;
  const files = readdirSync(pkgDir);
  const licFile = files.find((f) => /^licen[cs]e(\.(md|txt))?$/i.test(f));
  if (!licFile) return null;
  return readFileSync(join(pkgDir, licFile), "utf8").trim();
};

const visit = (name) => {
  if (seen.has(name)) return;
  const pkgDir = join(root, "node_modules", name);
  const file = join(pkgDir, "package.json");
  if (!existsSync(file)) return;
  const p = read(file);
  const license =
    typeof p.license === "string"
      ? p.license
      : p.license?.type ?? (Array.isArray(p.licenses) ? p.licenses.map((l) => l.type).join(" OR ") : "UNKNOWN");

  if (/\b(AGPL|LGPL|GPL)\b/i.test(license)) {
    console.error(`ERROR: Copyleft license detected in production dependency ${name}@${p.version}: ${license}`);
    process.exit(1);
  }

  const rawHome = p.homepage ?? (typeof p.repository === "string" ? p.repository : p.repository?.url ?? "");
  const homepage = normalizeUrl(rawHome);
  const licenseText = readLicenseFile(pkgDir);
  seen.set(name, { name, version: p.version, license, homepage, licenseText });
  for (const dep of Object.keys(p.dependencies ?? {})) visit(dep);
};

for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep);

const list = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const tsEntries = list.map(({ name, version, license, homepage }) => ({ name, version, license, homepage }));
const outTs = `// GENERATED by scripts/gen-licenses.mjs — do not edit. ${tsEntries.length} production packages.\nexport interface LicenseEntry { name: string; version: string; license: string; homepage: string }\nexport const LICENSES: readonly LicenseEntry[] = ${JSON.stringify(tsEntries, null, 1)};\n`;
writeFileSync(join(root, "src/app/pro/licenses.generated.ts"), outTs);

const mdLines = [
  "# Third-Party Licenses",
  "",
  "**Kekenik Shader** is released under the [MIT License](LICENSE).",
  "This file lists all production dependencies (direct and transitive) bundled with the application and their respective open-source licenses.",
  "",
  "No copyleft (`GPL`, `LGPL`, `AGPL`) packages are present in the production dependency tree.",
  "",
  "## Summary of Production Dependencies",
  "",
  "| Package | Version | License | Homepage / Repository |",
  "|---|---|---|---|",
  ...list.map((l) => `| \`${l.name}\` | \`${l.version}\` | \`${l.license}\` | ${l.homepage ? `[${l.homepage}](${l.homepage})` : "—"} |`),
  "",
  "---",
  "",
  "## Full License Texts",
  "",
];

for (const l of list) {
  mdLines.push(`### ${l.name} (${l.version}) — ${l.license}`);
  mdLines.push("");
  if (l.homepage) {
    mdLines.push(`Homepage: <${l.homepage}>`);
    mdLines.push("");
  }
  if (l.licenseText) {
    mdLines.push("```text");
    mdLines.push(l.licenseText);
    mdLines.push("```");
  } else {
    mdLines.push(`Licensed under ${l.license}.`);
  }
  mdLines.push("");
}

writeFileSync(join(root, "THIRD_PARTY_LICENSES.md"), mdLines.join("\n"));
console.log(`${list.length} production packages verified (0 copyleft); licenses: ${[...new Set(list.map((l) => l.license))].join(", ")}`);
