import { mkdirSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { runSweep, type SweepResult } from "./helpers/sweep";

const results = runSweep();
describe("fixG.sweep — every node × every Godot profile × {main, helper function}", () => {
  it("fixG.sweep.coverage", () => {
    const nodes = new Set(results.map((r) => r.node));
    expect(nodes.size).toBeGreaterThan(100);
    const counts = results.reduce<Record<string, number>>((a, r) => ((a[r.status] = (a[r.status] ?? 0) + 1), a), {});
    console.log("SWEEP", JSON.stringify(counts), "nodes", nodes.size);
    expect(counts.OK ?? 0).toBeGreaterThan(100);
  });
  it("fixG.sweep.zero-broken", () => {
    const broken = results.filter((r) => r.status === "BROKEN");
    expect(broken.map((b) => `${b.node} [${b.profile}/${b.variant}] ${b.detail}`)).toEqual([]);
  });
  it("fixG.sweep.write-matrix", () => {
    mkdirSync("docs", { recursive: true });
    writeFileSync("docs/EXPORT_MATRIX.md", matrix(results), "utf8");
  });
});

function matrix(rs: SweepResult[]): string {
  const profiles = [...new Set(rs.map((r) => r.profile))];
  const nodes = [...new Set(rs.map((r) => r.node))].sort();
  const cell = (n: string, p: string): string => {
    const x = rs.filter((r) => r.node === n && r.profile === p);
    if (!x.length) return "–";
    const worst = x.some((r) => r.status === "BROKEN") ? "BROKEN" : x.some((r) => r.status === "UNSUPPORTED") ? "UNSUP" : x.every((r) => r.status === "SKIP") ? "skip" : "OK";
    return worst;
  };
  const L = [
    "# Godot export matrix",
    "",
    "Generated by `tests/fixG.sweep.test.ts` (do not edit). Each registry node is exported alone (non-default inline inputs) for every Godot profile,",
    "once in the main graph and once inside a subgraph (= a generated helper function — the place where built-ins are illegal), then checked by the strict",
    "Godot validator. **OK** = valid by the validator; **UNSUP** = a clean graph diagnostic (`E_NODE_UNSUPPORTED_TARGET` …) and no code emitted; **BROKEN** = code emitted that the validator rejects (must be zero); **skip** = no standalone value output (texture / structural nodes).",
    "",
    `Totals: ${["OK", "UNSUPPORTED", "BROKEN", "SKIP"].map((s) => `${s} ${rs.filter((r) => r.status === s).length}`).join(" · ")} (node × profile × variant runs)`,
    "",
    `| Node | ${profiles.join(" | ")} |`,
    `|---|${profiles.map(() => "---").join("|")}|`,
    ...nodes.map((n) => `| \`${n}\` | ${profiles.map((p) => cell(n, p)).join(" | ")} |`),
    "",
    "## Unsupported on Godot (diagnosed, with reason)",
    "",
  ];
  const seen = new Set<string>();
  for (const r of rs.filter((x) => x.status === "UNSUPPORTED")) {
    const k = `${r.node}|${r.profile}`;
    if (seen.has(k)) continue;
    seen.add(k);
    L.push(`- \`${r.node}\` (${r.profile}): ${r.detail.replace(/\n/g, " ")}`);
  }
  const broken = rs.filter((r) => r.status === "BROKEN");
  L.push("", `## BROKEN (${broken.length})`, "", ...(broken.length ? broken.map((b) => `- \`${b.node}\` ${b.profile}/${b.variant}: ${b.detail}`) : ["none"]), "");
  return L.join("\n");
}
